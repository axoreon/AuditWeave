"""Create an Alembic migration with a sequential, readable filename.

The Alembic revision ID inside the generated file remains authoritative and is
not changed. Only the newly generated filename is renamed.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
import unicodedata
from pathlib import Path


REPOSITORY_ROOT = Path(__file__).resolve().parents[1]
BACKEND_DIR = REPOSITORY_ROOT / "backend"
VERSIONS_DIR = BACKEND_DIR / "migrations" / "versions"
SEQUENCE_PATTERN = re.compile(r"^(\d{4})_")
MAX_SLUG_LENGTH = 64


def migration_files(versions_dir: Path = VERSIONS_DIR) -> list[Path]:
    return sorted(
        path
        for path in versions_dir.glob("*.py")
        if path.name != "__init__.py"
    )


def next_sequence(files: list[Path]) -> int:
    prefixes = [
        int(match.group(1))
        for path in files
        if (match := SEQUENCE_PATTERN.match(path.name))
    ]
    # Legacy files do not have numeric prefixes. Counting them reserves their
    # place in history, so this repository's first standardized file is 0009.
    next_number = max(max(prefixes, default=0), len(files)) + 1
    if next_number > 9999:
        raise RuntimeError("Migration sequence exceeds the four-digit filename limit.")
    return next_number


def slugify(message: str) -> str:
    normalized = unicodedata.normalize("NFKD", message)
    ascii_message = normalized.encode("ascii", "ignore").decode("ascii").lower()
    slug = re.sub(r"[^a-z0-9]+", "_", ascii_message).strip("_")
    slug = slug[:MAX_SLUG_LENGTH].rstrip("_")
    if not slug:
        raise ValueError("Migration message must contain at least one letter or number.")
    return slug


def ensure_single_head() -> None:
    result = subprocess.run(
        [sys.executable, "-m", "alembic", "heads"],
        cwd=BACKEND_DIR,
        check=False,
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        detail = result.stderr.strip() or result.stdout.strip()
        raise RuntimeError(f"Unable to inspect Alembic heads: {detail}")

    heads = [line for line in result.stdout.splitlines() if line.strip().endswith("(head)")]
    if len(heads) != 1:
        raise RuntimeError(
            f"Expected exactly one Alembic head before generation; found {len(heads)}. "
            "Resolve migration branches before creating another revision."
        )


def create_migration(message: str, dry_run: bool = False) -> Path:
    files_before = migration_files()
    sequence = next_sequence(files_before)
    target = VERSIONS_DIR / f"{sequence:04d}_{slugify(message)}.py"

    if target.exists():
        raise FileExistsError(f"Target migration already exists: {target}")

    ensure_single_head()
    command = [
        sys.executable,
        "-m",
        "alembic",
        "revision",
        "--autogenerate",
        "-m",
        message,
    ]

    if dry_run:
        print(f"Next migration: {target.relative_to(REPOSITORY_ROOT)}")
        print(f"Command: {' '.join(command)}")
        return target

    result = subprocess.run(command, cwd=BACKEND_DIR, check=False)
    if result.returncode != 0:
        raise RuntimeError("Alembic revision generation failed; no migration was renamed.")

    files_after = set(migration_files())
    generated = sorted(files_after - set(files_before))
    if len(generated) != 1:
        names = ", ".join(path.name for path in generated) or "none"
        raise RuntimeError(
            "Expected Alembic to generate exactly one migration file, "
            f"but found: {names}. No file was renamed."
        )

    generated_path = generated[0]
    generated_path.rename(target)
    print(f"Created {target.relative_to(REPOSITORY_ROOT)}")
    print("Review upgrade() and downgrade() before committing.")
    return target


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Create an autogenerated Alembic migration with an NNNN_slug.py filename."
    )
    parser.add_argument("message", help="Short migration description, quoted when it contains spaces.")
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Show the next filename and Alembic command without creating a migration.",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    try:
        create_migration(args.message.strip(), dry_run=args.dry_run)
    except (FileExistsError, RuntimeError, ValueError) as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
